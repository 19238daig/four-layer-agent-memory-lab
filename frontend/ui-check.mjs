import {chromium} from 'playwright-core';
import fs from 'node:fs/promises';
import path from 'node:path';
const out=path.resolve('../artifacts/browser');
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1050},permissions:['clipboard-read','clipboard-write'],reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8010/',{waitUntil:'domcontentloaded'});
await page.locator('.connection').filter({hasText:'实时同步'}).waitFor();
await page.screenshot({path:path.join(out,'studio-empty.png'),fullPage:true});
await page.getByRole('heading',{name:'录入日常偏好',exact:true}).waitFor();
if((await page.locator('body').innerText()).includes('PowerShell'))throw Error('Terminal instructions should not be visible');
await page.screenshot({path:path.join(out,'interactive-demo.png'),fullPage:true});
await page.getByLabel('选择用户空间').selectOption('walkthrough');
await page.getByRole('button',{name:'四层总览',exact:true}).click();
await page.locator('.record-row').first().waitFor();
await page.screenshot({path:path.join(out,'overview-populated.png'),fullPage:true});
await page.locator('.record-row').first().click();
await page.getByLabel('记忆记录详情').waitFor();
await page.getByRole('button',{name:'输入与来源',exact:true}).click();
await page.screenshot({path:path.join(out,'artifact-inspector.png'),fullPage:true});
await page.getByRole('button',{name:'关闭详情',exact:true}).click();
await page.getByRole('button',{name:'引用追踪',exact:true}).click();
const choices=await page.getByLabel('选择要追踪的回答').locator('option').evaluateAll(nodes=>nodes.map(n=>({value:n.value,text:n.textContent})));
const citedAnswer=choices.find(x=>x.text.includes('day4'));
if(citedAnswer)await page.getByLabel('选择要追踪的回答').selectOption(citedAnswer.value);
await page.screenshot({path:path.join(out,'trace.png'),fullPage:true});
await page.getByRole('button',{name:'方案对比',exact:true}).click();
await page.screenshot({path:path.join(out,'comparison.png'),fullPage:true});
const widths=[1440,1024,768,390];
const layouts=[];
for(const width of widths){
 await page.setViewportSize({width,height:900});
 await page.getByRole('button',{name:'四层总览',exact:true}).click();
 const layout=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
 layouts.push(layout);
 await page.screenshot({path:path.join(out,`overview-${width}.png`),fullPage:true});
 if(layout.scrollWidth>width)throw Error(`Horizontal overflow at ${width}: ${layout.scrollWidth}`);
}
await fs.writeFile(path.join(out,'report.json'),JSON.stringify({errors,layouts,frontendDemo:true},null,2));
await browser.close();
if(errors.length)throw Error(errors.join('\n'));
console.log(JSON.stringify({errors,layouts,frontendDemo:true}));
